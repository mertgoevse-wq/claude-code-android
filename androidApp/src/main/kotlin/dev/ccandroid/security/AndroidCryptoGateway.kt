package dev.ccandroid.security

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import dev.ccandroid.core.CryptoGateway
import java.security.KeyStore
import java.security.KeyStoreException
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext

/**
 * The Android Keystore implementation of [CryptoGateway], per
 * `docs/07-integrations/secrets.md` §Storage: one AES-256-GCM key per alias,
 * hardware-backed where the device has a secure element, no user
 * authentication requirement so a run can decrypt in the background.
 *
 * Wire format: `iv (12 bytes) || ciphertext+tag`. The IV is generated by the
 * platform cipher and travels with the payload, so a caller never handles a
 * raw IV. The Keystore import lives in this file only
 * (`KeystoreOnlyInOneFile`).
 *
 * This class is exercised on the device; the store composition around it is
 * unit-tested against a fake gateway in `KeystoreSecretStoreTest`.
 */
public class AndroidCryptoGateway : CryptoGateway {

    private val keyStore: KeyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }

    override suspend fun encrypt(alias: String, plainText: ByteArray): ByteArray = withContext(Dispatchers.IO) {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, secretKey(alias))
        val cipherText = cipher.doFinal(plainText)
        cipher.iv + cipherText
    }

    override suspend fun decrypt(alias: String, cipherText: ByteArray): ByteArray = withContext(Dispatchers.IO) {
        require(cipherText.size > IV_LENGTH) { "ciphertext is shorter than its own IV" }
        val iv = cipherText.copyOfRange(0, IV_LENGTH)
        val body = cipherText.copyOfRange(IV_LENGTH, cipherText.size)
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, secretKey(alias), GCMParameterSpec(TAG_LENGTH_BITS, iv))
        cipher.doFinal(body)
    }

    override suspend fun deleteKey(alias: String): Boolean = withContext(Dispatchers.IO) {
        try {
            keyStore.deleteEntry(alias)
            true
        } catch (_: KeyStoreException) {
            false
        }
    }

    override suspend fun hasKey(alias: String): Boolean = withContext(Dispatchers.IO) {
        keyStore.containsAlias(alias)
    }

    private fun secretKey(alias: String): SecretKey {
        val existing = keyStore.getKey(alias, null) as? SecretKey
        if (existing != null) return existing

        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
        generator.init(
            KeyGenParameterSpec.Builder(alias, KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT)
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(KEY_SIZE_BITS)
                .setUserAuthenticationRequired(false)
                .build(),
        )
        return generator.generateKey()
    }

    private companion object {
        const val ANDROID_KEYSTORE = "AndroidKeyStore"
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val KEY_SIZE_BITS = 256
        const val TAG_LENGTH_BITS = 128
        const val IV_LENGTH = 12
    }
}
